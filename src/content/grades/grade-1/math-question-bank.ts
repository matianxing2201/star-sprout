/** 一年级上册数学第一单元练习题：每个知识点先安排 4 道递进变式。 */
type ChoiceId = "A" | "B" | "C" | "D";
type FourChoices = readonly [string, string, string, string];

const choiceIds: readonly ChoiceId[] = ["A", "B", "C", "D"];

function makeQuestion(
  id: string,
  knowledgePointId: string,
  prompt: string,
  choiceTexts: FourChoices,
  answerId: ChoiceId,
  explanation: string,
  illustrationAlt: string
) {
  return {
    id,
    topicId: "grade-1-math-u1",
    knowledgePointId,
    prompt,
    illustration: `/images/questions/g1-math/${id}.webp`,
    illustrationAlt,
    choices: choiceTexts.map((text, index) => ({
      id: choiceIds[index]!,
      text,
    })),
    answerId,
    explanation,
  };
}

